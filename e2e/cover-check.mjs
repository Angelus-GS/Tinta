import puppeteer from 'puppeteer-core';
import { lookup } from 'node:dns/promises';
const proxyEnv = process.env.https_proxy || '';
const u = new URL(proxyEnv);
const { address, family } = await lookup(u.hostname);
const proxy = `${u.protocol}//${family === 6 ? `[${address}]` : address}:${u.port}`;
const browser = await puppeteer.launch({ executablePath: '/home/hatch/workspace/tinta/e2e/chrome-headless-shell/linux-155.0.8059.84/chrome-headless-shell-linux64/chrome-headless-shell', args: ['--no-sandbox', '--ignore-certificate-errors', `--proxy-server=${proxy}`, '--proxy-bypass-list=localhost;127.0.0.1'], protocolTimeout: 120000 });
const page = await browser.newPage();
await page.setUserAgent('Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/155.0.0.0 Safari/537.36');
await page.evaluateOnNewDocument((v) => { try { localStorage.setItem('tinta.proxyBase', v); } catch {} }, 'https://tinta-proxy.nacho-divan-7j.workers.dev');
await page.goto('http://localhost:8788/', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('button[data-install="en.weebcentral"]', { timeout: 30000 });
await page.click('button[data-install="en.weebcentral"]');
await page.waitForSelector('button[data-open="en.weebcentral"]', { timeout: 90000 });
await page.click('button[data-open="en.weebcentral"]');
await page.waitForSelector('#search-input', { visible: true });
await page.type('#search-input', 'One Piece');
await page.keyboard.press('Enter');
await page.waitForFunction(() => document.querySelectorAll('#results .card').length > 0, { timeout: 120000 });
await new Promise((r) => setTimeout(r, 5000));
const info = await page.$$eval('#results .card img', (imgs) => ({ total: imgs.length, loaded: imgs.filter((i) => i.complete && i.naturalWidth > 0).length, sample: imgs[0] ? imgs[0].src.slice(0, 100) : null }));
console.log('PORTADAS WC:', JSON.stringify(info));
await browser.close();
